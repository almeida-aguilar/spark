#!/usr/bin/env node
/**
 * Genera THIRD_PARTY_LICENSES.md a partir de package-lock.json y de las licencias
 * declaradas en los paquetes instalados (node_modules).
 *
 * Solo incluye dependencias de producción (las de desarrollo se omiten) y agrupa
 * por licencia. Ejecutar desde la raíz del repositorio:
 *
 *   node scripts/generate-third-party-licenses.js
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const LOCK = path.join(ROOT, 'package-lock.json');
const OUTPUT = path.join(ROOT, 'THIRD_PARTY_LICENSES.md');

const readJson = file => JSON.parse(fs.readFileSync(file, 'utf8'));

const licenseOf = (name, lockLicense) => {
    if (lockLicense) {
        return typeof lockLicense === 'string' ? lockLicense : lockLicense.type;
    }
    const manifest = path.join(ROOT, 'node_modules', name, 'package.json');
    if (!fs.existsSync(manifest)) return null;
    try {
        const pkg = readJson(manifest);
        if (pkg.license) {
            return typeof pkg.license === 'string' ? pkg.license : pkg.license.type;
        }
        if (Array.isArray(pkg.licenses)) {
            return pkg.licenses.map(l => (typeof l === 'string' ? l : l.type)).join(' OR ');
        }
        // SPARK: sin campo "license": se busca un archivo de licencia en el paquete.
        const dir = path.join(ROOT, 'node_modules', name);
        const files = fs.readdirSync(dir);
        const licenseFile = files.find(f => /^licen[cs]e/i.test(f));
        if (licenseFile) {
            return `not declared (see ${licenseFile})`;
        }
        return null;
    } catch (e) {
        return null;
    }
};

const lock = readJson(LOCK);
const entries = Object.entries(lock.packages || {})
    .filter(([name, meta]) => name.startsWith('node_modules/') && !meta.dev)
    .map(([name, meta]) => {
        const packageName = name.slice('node_modules/'.length);
        return {
            name: packageName,
            version: meta.version,
            license: licenseOf(packageName, meta.license)
        };
    })
    .filter(entry => entry.version);

const byLicense = new Map();
for (const entry of entries) {
    const license = entry.license || 'UNKNOWN (no license declared)';
    if (!byLicense.has(license)) byLicense.set(license, []);
    byLicense.get(license).push(entry);
}

const lines = [
    '# Third-party licenses',
    '',
    'This file is generated by `scripts/generate-third-party-licenses.js`.',
    'Do not edit it by hand.',
    '',
    'It lists the production dependencies of the monorepo packages and the license',
    'declared by each one. Full license texts are distributed with the packages',
    'themselves inside `node_modules/` (each package keeps its own LICENSE file).',
    '',
    `Total production dependencies: ${entries.length}.`,
    ''
];

for (const license of [...byLicense.keys()].sort()) {
    lines.push(`## ${license}`, '');
    lines.push('| Package | Version |', '| --- | --- |');
    for (const entry of byLicense.get(license).sort((a, b) => a.name.localeCompare(b.name))) {
        lines.push(`| ${entry.name} | ${entry.version} |`);
    }
    lines.push('');
}

fs.writeFileSync(OUTPUT, `${lines.join('\n')}\n`);
console.log(`Wrote ${OUTPUT} with ${entries.length} production dependencies.`);
